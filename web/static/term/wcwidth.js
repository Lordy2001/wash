function inTable(cp, t) {
  let lo = 0, hi = t.length - 1;
  if (cp < t[0][0] || cp > t[hi][1]) return false;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (cp > t[mid][1]) lo = mid + 1;
    else if (cp < t[mid][0]) hi = mid - 1;
    else return true;
  }
  return false;
}

const cache = new Map();

/** wcwidth returns 0, 1 or 2 cells for a code point. */
export function wcwidth(cp) {
  if (cp < 0x300) return cp < 0x20 || (cp >= 0x7f && cp < 0xa0) ? 0 : (cp === 0xad ? 1 : 1);
  let w = cache.get(cp);
  if (w !== undefined) return w;
  w = cp === 0x200d ? 0 : inTable(cp, ZERO) ? 0 : inTable(cp, WIDE) ? 2 : 1;
  if (cache.size < 65536) cache.set(cp, w);
  return w;
}
